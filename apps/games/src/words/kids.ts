const ROWS = KIDS.map(([emoji, words]) => ({ emoji, words: words.split('|') }));

export const KIDS_WORDS = Object.fromEntries(LANGS.map((lang, i) => [lang, ROWS.map((r) => r.words[i])])) as Record<
  Lang,
  string[]
>;

const PICTURES = new Map(ROWS.flatMap(({ emoji, words }) => words.map((w) => [w.toLowerCase(), emoji] as const)));

/** The picture of a kids word, or null for a word outside the list. */
export function pictureOf(word: string | null | undefined): string | null {
  return (word && PICTURES.get(word.toLowerCase())) || null;
}
