export const dicts: Record<Lang, Record<Key, string>> = { en, ru, de, fr, es, zh, ja, ko, nb };

function startLang(): Lang {
  const saved = load('lang');
  if (isLang(saved)) return saved;
  const code = typeof navigator === 'undefined' ? '' : navigator.language.toLowerCase().slice(0, 2);
  if (code === 'no' || code === 'nn') return 'nb';
  return isLang(code) ? code : 'en';
}

export const lang = signal<Lang>(startLang());

export function setLang(next: Lang): void {
  lang.value = next;
  save('lang', next);
  document.documentElement.lang = next;
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return dicts[lang.value][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
}

export function chatText(m: Extract<ChatMsg, { kind: 'sys' }>): string {
  return t(`sys_${m.key}` as Key, { name: m.name ?? '', word: m.word ?? '' });
}
